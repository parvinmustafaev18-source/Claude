// В тексте разметка **жирный** и `моноширинный` — так проще править.
// Разбор в два прохода: сначала жирные куски, потом внутри каждого куска —
// моноширинные. Одним регулярным выражением не обойтись: **`LIRBUILD`** —
// вложенная разметка, а «(*.txt)» ломает жадный поиск закрывающих звёздочек.
function runs(text) {
  const out = [];
  const re = /\*\*(.+?)\*\*/g;
  let last = 0, m;
  while ((m = re.exec(text)) !== null) {
    if (m.index > last) pushCode(out, text.slice(last, m.index), false);
    pushCode(out, m[1], true);
    last = m.index + m[0].length;
  }
  if (last < text.length) pushCode(out, text.slice(last), false);
  return out;
}

function pushCode(out, text, bold) {
  const re = /`([^`]+)`/g;
  let last = 0, m;
  while ((m = re.exec(text)) !== null) {
    if (m.index > last) out.push(new TextRun({ text: text.slice(last, m.index), bold }));
    out.push(new TextRun({ text: m[1], bold, font: "Consolas", size: 20 }));
    last = m.index + m[0].length;
  }
  if (last < text.length) out.push(new TextRun({ text: text.slice(last), bold }));
}

